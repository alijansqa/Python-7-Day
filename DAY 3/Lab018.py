# SETS {}

my_set = {1,2,3,4,5,6,7}
print(my_set)

my_set = {1,2,3,4,4,5,6,7} # extra duplicate 4 will be removed
print(my_set)

# for finding type
print(type(my_set))

# LIST []
# Duplicates are allowed
my_list = [1,2,3,4,5,6,7]
my_list1 = [1,2,3,4,4,5,6,7]
print(my_list)
print(my_list1)
print(type(my_list))


